class I18n {
    constructor() {
        this.translations = translations;
        
        const savedLang = localStorage.getItem('language');
        if (savedLang) {
            this.currentLang = savedLang;
        } else {
            this.currentLang = this.isDachVisitor() ? 'de' : 'en';
        }
        
        this.currentLocale = this.detectLocale();
        document.documentElement.lang = this.currentLang;
    }

    getBrowserLanguageCodes() {
        const languages = Array.isArray(navigator.languages) && navigator.languages.length
            ? navigator.languages
            : [navigator.language || navigator.userLanguage || ''];

        return languages
            .filter(Boolean)
            .map(language => language.toLowerCase());
    }

    getRegionFromLanguageCode(languageCode) {
        const parts = languageCode.split('-');
        return parts.length > 1 ? parts[1] : '';
    }

    getTimeZone() {
        try {
            return Intl.DateTimeFormat().resolvedOptions().timeZone || '';
        } catch (error) {
            return '';
        }
    }

    isDachVisitor() {
        const dachRegions = ['ch', 'de', 'at'];
        const dachTimeZones = ['Europe/Zurich', 'Europe/Berlin', 'Europe/Vienna', 'Europe/Busingen'];
        const languageCodes = this.getBrowserLanguageCodes();

        const hasDachGermanLocale = languageCodes.some(languageCode => {
            const region = this.getRegionFromLanguageCode(languageCode);
            return languageCode.startsWith('de-') && dachRegions.includes(region);
        });

        if (hasDachGermanLocale) return true;

        const hasGermanLanguagePreference = languageCodes.some(languageCode => languageCode === 'de');
        return hasGermanLanguagePreference && dachTimeZones.includes(this.getTimeZone());
    }

    detectLocale() {
        // Try to get from localStorage first
        const savedLocale = localStorage.getItem('locale');
        if (savedLocale) return savedLocale;

        // Detect from browser
        const browserLang = this.getBrowserLanguageCodes()[0] || '';
        const langCode = browserLang.toLowerCase();
        
        // UK locales
        if (langCode.startsWith('en-gb') || langCode.startsWith('en-ie')) {
            return 'uk';
        }
        
        // US locale
        if (langCode.startsWith('en-us')) {
            return 'us';
        }
        
        const europeanRegions = ['de', 'at', 'ch', 'fr', 'it', 'es', 'nl', 'be', 'pl', 'pt', 'ro', 'hu', 'cz', 'sk', 'si', 'bg', 'hr', 'gr', 'fi', 'se', 'dk', 'no', 'ee', 'lv', 'lt', 'ie'];
        const region = this.getRegionFromLanguageCode(langCode);
        if (europeanRegions.includes(region) || this.isDachVisitor()) {
            return 'eu';
        }
        
        // Default to US for other English speakers and non-European countries
        if (langCode.startsWith('en')) {
            return 'us';
        }
        
        // Default to US for unknown locales
        return 'us';
    }

    getCurrency() {
        switch (this.currentLocale) {
            case 'uk':
                return '£';
            case 'us':
                return '$';
            case 'eu':
                return '€';
            default:
                return '$';
        }
    }

    getPriceText() {
        const currency = this.getCurrency();
        if (this.currentLang === 'de') {
            return `Dann 2.99${currency}/Woche`;
        }
        return `Then ${currency}2.99/Week`;
    }

    setLanguage(lang) {
        if (!translations[lang]) return;
        this.currentLang = lang;
        localStorage.setItem('language', lang);
        document.documentElement.lang = lang;
        this.updateContent();
        this.updateActiveState();
        this.emitChange();
    }

    // Lets non-data-i18n code (e.g. the JS-driven hero demo) re-render its
    // own strings whenever the active language changes.
    emitChange() {
        document.dispatchEvent(new CustomEvent('i18n:changed', {
            detail: { lang: this.currentLang }
        }));
    }

    updateContent() {
        // The document <title> is translated per page via <title data-i18n="...">
        // (handled by the generic [data-i18n] loop below), so pages without a
        // title key keep their own server-rendered title.
        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (this.translations[this.currentLang][key] !== undefined) {
                let text = this.translations[this.currentLang][key];
                
                // Special handling for price_highlight to use locale-based currency
                if (key === 'price_highlight') {
                    text = this.getPriceText();
                }
                
                // If the element has children (like bold tags inside), we might need to be careful
                // For now, we assume simple text replacement or innerHTML if it contains HTML
                // Using innerHTML to allow for formatting if needed in translations
                element.innerHTML = text;
            }
        });

        // Update attributes
        const attrElements = document.querySelectorAll('[data-i18n-attr]');
        attrElements.forEach(element => {
            const attrConfig = element.getAttribute('data-i18n-attr');
            if (attrConfig) {
                const [attrName, key] = attrConfig.split(':');
                if (this.translations[this.currentLang][key] !== undefined) {
                    element.setAttribute(attrName, this.translations[this.currentLang][key]);
                }
            }
        });
    }

    updateActiveState() {
        const buttons = document.querySelectorAll('.lang-btn');
        buttons.forEach(btn => {
            if (btn.dataset.lang === this.currentLang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });
    }

    t(key) {
        if (this.translations[this.currentLang] && this.translations[this.currentLang][key] !== undefined) {
            return this.translations[this.currentLang][key];
        }
        return key;
    }

    init() {
        // Update locale on init (in case browser language changed)
        this.currentLocale = this.detectLocale();
        this.updateContent();
        // Create language switcher if it doesn't exist
        this.injectSwitcher();
        // Let JS-driven demos sync to the detected language on first load.
        this.emitChange();
    }
    
    injectSwitcher() {
        // The manual language switcher lives in the footer. If the page has no
        // footer, fall back to a small floating switcher pinned to the corner so
        // manual switching is always available.
        if (!document.querySelector('.lang-switcher')) {
            const switcher = document.createElement('div');
            switcher.innerHTML = `
                <span class="lang-switcher-globe" aria-hidden="true">🌐</span>
                <button class="lang-btn" type="button" data-lang="de" onclick="i18n.setLanguage('de')">DE</button>
                <span class="lang-separator">|</span>
                <button class="lang-btn" type="button" data-lang="en" onclick="i18n.setLanguage('en')">EN</button>
            `;

            // Prefer the footer's brand column (under the copyright line), then
            // any <footer>, and only float it as a last resort.
            const footerBrand = document.querySelector('.q-footer .q-footer-brand');
            const genericFooter = document.querySelector('footer');

            if (footerBrand) {
                switcher.className = 'lang-switcher lang-switcher-footer';
                footerBrand.appendChild(switcher);
            } else if (genericFooter) {
                switcher.className = 'lang-switcher lang-switcher-footer';
                genericFooter.appendChild(switcher);
            } else {
                switcher.className = 'lang-switcher lang-switcher-floating';
                document.body.appendChild(switcher);
            }

            if (!document.getElementById('lang-switcher-styles')) {
                const style = document.createElement('style');
                style.id = 'lang-switcher-styles';
                style.textContent = `
                    .lang-switcher {
                        display: flex;
                        align-items: center;
                        gap: 6px;
                        font-size: 0.9rem;
                        z-index: 100;
                    }
                    .lang-switcher-globe {
                        opacity: 0.6;
                        font-size: 0.95em;
                        line-height: 1;
                    }
                    .lang-btn {
                        background: none;
                        border: none;
                        cursor: pointer;
                        font-family: inherit;
                        color: inherit;
                        opacity: 0.55;
                        padding: 2px 5px;
                        font-weight: 700;
                        transition: opacity 0.15s;
                    }
                    .lang-btn:hover { opacity: 0.85; }
                    .lang-btn.active {
                        opacity: 1;
                        text-decoration: underline;
                        text-underline-offset: 3px;
                    }
                    .lang-separator { opacity: 0.3; }

                    /* In the footer: left-aligned, under the copyright line */
                    .lang-switcher-footer {
                        justify-content: flex-start;
                        margin-top: 2px;
                    }

                    /* Floating fallback for pages without a footer */
                    .lang-switcher-floating {
                        position: fixed;
                        bottom: 16px;
                        right: 16px;
                        background: rgba(255, 255, 255, .92);
                        border: 1px solid rgba(0, 0, 0, .12);
                        border-radius: 999px;
                        padding: 5px 12px;
                        box-shadow: 0 2px 10px rgba(0, 0, 0, .12);
                        backdrop-filter: blur(4px);
                    }
                `;
                document.head.appendChild(style);
            }
        }

        this.updateActiveState();
    }
}

window.i18n = new I18n();

window.selectSub = function(type) {
    // Update UI classes
    document.querySelectorAll('.sub-item').forEach(c => c.classList.remove('active'));
    const card = document.getElementById('card-' + type);
    if (card) card.classList.add('active');
    
    // Update info text
    const infoArea = document.getElementById('sub-info-area');
    const key = 'rewards_subs_' + type + '_info';
    
    // Add special styling for boost
    if (type === 'boost') {
        infoArea.classList.add('boost-special');
    } else {
        infoArea.classList.remove('boost-special');
    }
    
    if (window.i18n && typeof window.i18n.t === 'function') {
        const text = window.i18n.t(key);
        if (text && text !== key) {
            infoArea.innerHTML = `<span data-i18n="${key}">${text}</span>`;
        }
    }
};

